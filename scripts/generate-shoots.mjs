// scripts/generate-shoots.mjs
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const SHOOTS_DIR = path.join(ROOT, 'content/shoots')
const OUT_FILE = path.join(ROOT, 'lib/generated-shoots.ts')

// Extract the "export const metadata = { ... }" object literal from an MDX file
function extractMetadata(source) {
  const match = source.match(
    /export\s+const\s+metadata\s*=\s*({[\s\S]*?})\s*(?:\n\s*(?:export|#|\/\*)|$)/
  )
  if (!match) throw new Error('No `export const metadata = { ... }` found')
  // `metadata` is a plain object literal, so eval'ing it in a sandbox is safe enough
  // provided you trust your own content files. For untrusted input, parse with a real parser.
  return new Function(`return (${match[1]})`)()
}

async function main() {
  let files = []
  try {
    files = (await fs.readdir(SHOOTS_DIR)).filter((f) => f.endsWith('.mdx'))
  } catch (err) {
    if (err.code === 'ENOENT') {
      console.warn(`[shoots] no content/shoots dir found — writing empty array`)
    } else {
      throw err
    }
  }

  const shoots = []
  for (const file of files) {
    const slug = file.replace(/\.mdx$/, '')
    const source = await fs.readFile(path.join(SHOOTS_DIR, file), 'utf8')
    const metadata = extractMetadata(source)
    shoots.push({
      slug,
      ...metadata,
      // Normalise the date to an ISO string so it serialises cleanly
      date:
        metadata.date instanceof Date
          ? metadata.date.toISOString()
          : new Date(metadata.date).toISOString(),
    })
  }

  shoots.sort((a, b) => new Date(b.date) - new Date(a.date))

  const banner = `// AUTO-GENERATED by scripts/generate-shoots.mjs — do not edit by hand.
// Run \`npm run gen:shoots\` (or \`npm run dev\` / \`npm run build\`) to regenerate.
`
  const body = `export const shoots = ${JSON.stringify(shoots, null, 2)} as const\n`

  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true })
  await fs.writeFile(OUT_FILE, banner + body, 'utf8')
  console.log(`[shoots] wrote ${shoots.length} shoot(s) to lib/generated-shoots.ts`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})